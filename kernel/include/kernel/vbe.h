/*
 * Quilon OS -- VGA Graphics Mode driver  (section 10.4)
 *
 * Provides a linear framebuffer terminal that replaces the VGA text-mode
 * driver when GRUB hands off a VESA/VBE framebuffer.
 *
 * How it fits together
 * --------------------
 * grub.cfg requests the mode:
 *   set gfxmode=800x600x32
 *   set gfxpayload=keep
 *
 * GRUB sets MULTIBOOT_FLAG_FB (bit 12) in multiboot_info_t.flags and fills
 * in the framebuffer_* fields.  kernel_main passes those fields to vbe_init().
 *
 * After vbe_init() returns true, every call to terminal_putchar / terminal_write
 * (tty.c) is transparently redirected to the VBE terminal.
 *
 * Host-side unit tests (test_vbe.c) include this header and exercise the
 * pure-C static-inline helpers: vbe_glyph_pixel() and vbe_pixel_offset().
 * Hardware-dependent code lives in vbe.c and is guarded by __is_kernel.
 */

