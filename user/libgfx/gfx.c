#include <gfx.h>
#include <stddef.h>

/* malloc/free: use explicit externs so gfx.c compiles both inside the user-space
 * cross-compiler (where user libc provides them) and on the host (where host
 * libc provides them).  This avoids pulling in a stdlib.h that may not have
 * malloc (the kernel libc/include/stdlib.h only declares abort).           */
extern void *malloc(size_t);
extern void  free(void *);

/* -- Syscall numbers ----------------------------------------------------- */

#define SYS_GFX_INFO   40
#define SYS_GFX_MAP    41
#define SYS_GFX_FLUSH  42

/* User VA where SYS_GFX_MAP places the shadow buffer (must match kernel). */
#define GFX_MAP_UADDR  0x60000000u

#ifdef __i386__
static inline int gfx_syscall0(uint32_t num)
{
    int ret;
    asm volatile("int $0x80" : "=a"(ret) : "a"(num) : "memory");
    return ret;
}

static inline int gfx_syscall1(uint32_t num, uint32_t a)
{
    int ret;
    asm volatile("int $0x80" : "=a"(ret) : "a"(num), "b"(a) : "memory");
    return ret;
}
#else
/* Host / non-i386: syscall stubs are no-ops so gfx.c compiles for testing. */
static inline int gfx_syscall0(uint32_t num) { (void)num; return -1; }
static inline int gfx_syscall1(uint32_t num, uint32_t a)
    { (void)num; (void)a; return -1; }
#endif

