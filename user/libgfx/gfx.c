/* -- Clip helpers -------------------------------------------------------- */

static void clip_rect(const canvas_t *c, int *x0, int *y0, int *x1, int *y1)
{
    /* Clamp to canvas */
    if (*x0 < 0) *x0 = 0;
    if (*y0 < 0) *y0 = 0;
    if (*x1 > c->w) *x1 = c->w;
    if (*y1 > c->h) *y1 = c->h;
    /* Apply active clip rect */
    if (c->has_clip) {
        if (*x0 < c->clip_x0) *x0 = c->clip_x0;
        if (*y0 < c->clip_y0) *y0 = c->clip_y0;
        if (*x1 > c->clip_x1) *x1 = c->clip_x1;
        if (*y1 > c->clip_y1) *y1 = c->clip_y1;
    }
}

static int pixel_visible(const canvas_t *c, int x, int y)
{
    if (x < 0 || y < 0 || x >= c->w || y >= c->h) return 0;
    if (c->has_clip &&
        (x < c->clip_x0 || x >= c->clip_x1 ||
         y < c->clip_y0 || y >= c->clip_y1)) return 0;
    return 1;
}

/* -- Canvas management --------------------------------------------------- */

canvas_t *canvas_create(int w, int h)
{
    if (w <= 0 || h <= 0) return NULL;
    canvas_t *c = (canvas_t *)malloc(sizeof(canvas_t));
    if (!c) return NULL;
    c->pixels = (uint32_t *)malloc((unsigned)(w * h) * sizeof(uint32_t));
    if (!c->pixels) { free(c); return NULL; }
    c->w       = w;
    c->h       = h;
    c->pitch   = w;
    c->has_clip = 0;
    c->clip_x0 = c->clip_y0 = c->clip_x1 = c->clip_y1 = 0;
    return c;
}

void canvas_free(canvas_t *c)
{
    if (!c) return;
    free(c->pixels);
    free(c);
}

/* -- Screen canvas ------------------------------------------------------- */

/* Static screen canvas — stored here so gfx_screen_init only maps once. */
static canvas_t screen_canvas;
static int      screen_mapped = 0;

canvas_t *gfx_screen_init(gfx_info_t *info)
{
    gfx_info_t local;
    if (gfx_syscall1(SYS_GFX_INFO, (uint32_t)(uintptr_t)&local) != 0)
        return NULL;

    uint32_t uaddr = (uint32_t)gfx_syscall0(SYS_GFX_MAP);
    if (uaddr == (uint32_t)-1) return NULL;

    if (info) *info = local;

    screen_canvas.pixels  = (uint32_t *)(uintptr_t)uaddr;
    screen_canvas.w       = (int)local.width;
    screen_canvas.h       = (int)local.height;
    screen_canvas.pitch   = (int)(local.pitch / 4); /* bytes → pixels */
    screen_canvas.has_clip = 0;
    screen_canvas.clip_x0 = screen_canvas.clip_y0 = 0;
    screen_canvas.clip_x1 = screen_canvas.clip_y1 = 0;
    screen_mapped = 1;
    return &screen_canvas;
}

void gfx_flush(void)
{
    gfx_syscall0(SYS_GFX_FLUSH);
}

/* -- Clip rectangle ------------------------------------------------------ */

void gfx_set_clip(canvas_t *c, rect_t r)
{
    if (!c) return;
    int x0 = r.x     < 0     ? 0     : r.x;
    int y0 = r.y     < 0     ? 0     : r.y;
    int x1 = r.x+r.w > c->w  ? c->w  : r.x+r.w;
    int y1 = r.y+r.h > c->h  ? c->h  : r.y+r.h;
    c->clip_x0 = x0; c->clip_y0 = y0;
    c->clip_x1 = x1; c->clip_y1 = y1;
    c->has_clip = (x0 < x1 && y0 < y1) ? 1 : 0;
}

void gfx_clear_clip(canvas_t *c)
{
    if (c) c->has_clip = 0;
}

/* -- Drawing primitives -------------------------------------------------- */

void gfx_fill(canvas_t *c, color_t col)
{
    if (!c) return;
    int n = c->h * c->pitch;
    for (int i = 0; i < n; i++)
        c->pixels[i] = col;
}

void gfx_fill_rect(canvas_t *c, rect_t r, color_t col)
{
    if (!c) return;
    int x0 = r.x, y0 = r.y, x1 = r.x + r.w, y1 = r.y + r.h;
    clip_rect(c, &x0, &y0, &x1, &y1);
    if (x0 >= x1 || y0 >= y1) return;

    for (int y = y0; y < y1; y++) {
        uint32_t *row = c->pixels + y * c->pitch + x0;
        for (int x = x0; x < x1; x++)
            *row++ = col;
    }
}

void gfx_draw_rect(canvas_t *c, rect_t r, color_t col)
{
    if (!c || r.w <= 0 || r.h <= 0) return;
    /* top and bottom edge */
    gfx_fill_rect(c, (rect_t){r.x, r.y,         r.w, 1      }, col);
    gfx_fill_rect(c, (rect_t){r.x, r.y + r.h-1, r.w, 1      }, col);
    /* left and right edge (avoid overdrawing corners) */
    gfx_fill_rect(c, (rect_t){r.x,         r.y+1, 1, r.h - 2}, col);
    gfx_fill_rect(c, (rect_t){r.x + r.w-1, r.y+1, 1, r.h - 2}, col);
}

void gfx_blit(canvas_t *dst, int dx, int dy,
              const canvas_t *src, rect_t sr)
{
    if (!dst || !src) return;
    /* Clamp source rect to src bounds */
    if (sr.x < 0) { dx -= sr.x; sr.w += sr.x; sr.x = 0; }
    if (sr.y < 0) { dy -= sr.y; sr.h += sr.y; sr.y = 0; }
    if (sr.x + sr.w > src->w) sr.w = src->w - sr.x;
    if (sr.y + sr.h > src->h) sr.h = src->h - sr.y;
    if (sr.w <= 0 || sr.h <= 0) return;

    for (int row = 0; row < sr.h; row++) {
        int sy = sr.y + row;
        int dy_ = dy + row;
        if (!pixel_visible(dst, dx, dy_) && !pixel_visible(dst, dx + sr.w - 1, dy_))
            continue; /* quick row check */
        for (int col = 0; col < sr.w; col++) {
            int sx = sr.x + col;
            int dx_ = dx + col;
            if (!pixel_visible(dst, dx_, dy_)) continue;
            dst->pixels[dy_ * dst->pitch + dx_] =
                src->pixels[sy  * src->pitch + sx];
        }
    }
}

void gfx_draw_line(canvas_t *c, int x0, int y0, int x1, int y1, color_t col)
{
    if (!c) return;
    int dx = x1 - x0, dy = y1 - y0;
    int sx = (dx < 0) ? -1 : 1;
    int sy = (dy < 0) ? -1 : 1;
    if (dx < 0) dx = -dx;
    if (dy < 0) dy = -dy;
    int err = dx - dy;
    while (1) {
        if (pixel_visible(c, x0, y0))
            c->pixels[y0 * c->pitch + x0] = col;
        if (x0 == x1 && y0 == y1) break;
        int e2 = err * 2;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 <  dx) { err += dx; y0 += sy; }
    }
}

void gfx_draw_text(canvas_t *c, int x, int y,
                   const char *str, color_t fg, color_t bg)
{
    if (!c || !str) return;
    int cx = x;
    for (const char *p = str; *p; p++, cx += GFX_CHAR_W) {
        unsigned int ch = (unsigned char)*p;
        if (ch >= 128) ch = '?';
        for (int row = 0; row < GFX_CHAR_H; row++) {
            /* Bottom 8 rows of the 16-row cell are background fill */
            uint8_t bits = (row < 8) ? gfx_font[ch][row] : 0;
            for (int col = 0; col < GFX_CHAR_W; col++) {
                int px = cx + col;
                int py = y + row;
                if (!pixel_visible(c, px, py)) continue;
                c->pixels[py * c->pitch + px] =
                    (bits & (0x80u >> col)) ? fg : bg;
            }
        }
    }
}
